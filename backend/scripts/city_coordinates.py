def get_city_coordinates(city: str, state: str) -> Optional[tuple[float, float]]:
    """
    Return (latitude, longitude) for a given US city and state.

    Lookup hierarchy:
        1. Exact city + state match
        2. State centroid fallback
        3. None if state is unrecognized

    Args:
        city: City name (e.g., "Chicago").
        state: Two-letter US state code (e.g., "IL").

    Returns:
        (latitude, longitude) tuple or None.
    """
    city_clean = city.strip().lower()
    state_clean = state.strip().upper()

    # Remove common trailing whitespace / encoding artifacts
    city_clean = city_clean.rstrip()

    coords = _CITY_COORDS.get((city_clean, state_clean))
    if coords:
        return coords

    # State centroid fallback
    state_coords = _STATE_CENTROIDS.get(state_clean)
    return state_coords
